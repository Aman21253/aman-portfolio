// Rebuilds server/src/knowledge.js (what the AI chat knows) from the content block in site/index.html.
// Run after you edit the portfolio:  node scripts/make-knowledge.mjs
import fs from 'node:fs';
const root = new URL('../', import.meta.url);
const html = fs.readFileSync(new URL('site/index.html', root), 'utf8');
const D = JSON.parse(html.match(/const D=(\{.*?\});\n/s)[1]);
const ABOUT = 'Education: B.Tech in Computer Science, Arya Institute of Engineering and Technology, Jaipur, 2022-2026, CGPA 7.7/10. Solved 180+ DSA problems on LeetCode. Certifications: NPTEL C Programming (IIT Kharagpur), Infosys Springboard Full Stack Development.';
const L = [`Name: ${D.profile.name}. Location: Bengaluru, India. Role: full-stack developer (Node.js, React). Email: ${D.profile.email}. GitHub: ${D.profile.github}. LinkedIn: ${D.profile.linkedin}.`, ABOUT, 'EXPERIENCE (five internships since 2024):'];
for (const j of D.jobs) { L.push(`- ${j.role} at ${j.co} (${j.when}):`); j.points.forEach((p) => L.push(`  * ${p}`)); }
L.push('PROJECTS:');
for (const p of D.projects) L.push(`- ${p.name}: ${p.text} Tech: ${p.stack.join(', ')}. ${p.hl.join(' ')}`);
L.push('GITHUB REPOSITORIES:');
for (const r of D.repos) L.push(`- ${r.name} (${r.lang}): ${r.desc} Tech: ${r.tech.join(', ')}. ${(r.hl || []).join(' ')}`);
L.push('SKILLS:');
for (const [g, a] of Object.entries(D.groups)) L.push(`- ${g}: ${a.join(', ')}`);
fs.writeFileSync(new URL('server/src/knowledge.js', root), `// Generated by scripts/make-knowledge.mjs. Do not edit by hand.\nexport default ${JSON.stringify(L.join('\n'))};\n`);
console.log('knowledge.js updated:', L.join('\n').length, 'characters');
